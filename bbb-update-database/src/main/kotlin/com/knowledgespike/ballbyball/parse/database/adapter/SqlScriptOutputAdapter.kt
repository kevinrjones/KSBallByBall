package com.knowledgespike.ballbyball.parse.database.adapter

import com.knowledgespike.ballbyball.parse.database.adapter.relational.RelationalMatchSession
import com.knowledgespike.ballbyball.parse.database.adapter.relational.RelationalRow
import com.knowledgespike.ballbyball.parse.database.adapter.relational.RelationalRowOperation
import com.knowledgespike.ballbyball.parse.database.adapter.relational.RelationalSink
import java.io.BufferedWriter
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardOpenOption
import java.time.LocalDate
import java.time.LocalDateTime

/** Writes an executable dialect-specific SQL script with stable keys within the script. */
abstract class SqlScriptOutputAdapter private constructor(
    private val context: ScriptContext
) : SessionBackedOutputAdapter(context.session) {
    protected constructor(output: Path, dialect: SqlDialect) : this(ScriptContext(output, dialect))

    override fun beginMatch() = context.beginMatch()

    override fun commit() = context.transaction.commit()

    override fun rollback() = context.transaction.rollback()

    override fun complete() = context.complete()

    override fun close() = context.close()
}

private class ScriptContext(output: Path, private val dialect: SqlDialect) {
    private val outputPath = output
    private val stagedPath = createStagedPath(output)
    private var writer: BufferedWriter = openWriter(stagedPath)
    private var closed = false
    val session = RelationalMatchSession(RelationalSink(::emitRow), IdentityCore())
    private val scriptTransaction = object : MatchTransactionParticipant {
        private var snapshot: TransactionSnapshot? = null

        override fun begin() {
            snapshot = TransactionSnapshot(Files.size(stagedPath))
        }

        override fun commit() {
            snapshot = null
        }

        override fun rollback() {
            val currentSnapshot = snapshot ?: return
            writer.flush()
            writer.close()
            Files.newByteChannel(stagedPath, StandardOpenOption.WRITE).use { channel ->
                channel.truncate(currentSnapshot.stagedSize)
            }
            writer = openWriter(stagedPath, append = true)
            snapshot = null
        }
    }
    val transaction = MatchTransaction(listOf(session.transactionParticipant(), scriptTransaction))

    init {
        writer.appendLine("-- Generated by bbb-update-database")
        RelationalSchemaSql.writeTo(writer, dialect)
        writer.appendLine(dialect.transactionStart)
    }

    fun beginMatch() {
        writer.flush()
        transaction.begin()
    }

    fun complete() {
        check(!closed) { "SQL script output is already closed" }
        check(!transaction.isActive) { "Cannot complete SQL script output with an active match transaction" }

        writer.appendLine("COMMIT;")
        writer.flush()
        writer.close()
        JournaledMatchReplace.replace(stagedPath, outputPath, JournaledReplaceKind.FILE)
        closed = true
    }

    fun close() {
        if (closed) return

        var failure: Exception? = null
        try {
            if (transaction.isActive) transaction.rollback()
        } catch (rollbackFailure: Exception) {
            failure = rollbackFailure
        }
        try {
            writer.close()
        } catch (closeFailure: Exception) {
            failure = failure.withSuppressed(closeFailure)
        }
        try {
            if (!JournaledMatchReplace.hasPendingJournal(outputPath, JournaledReplaceKind.FILE)) {
                Files.deleteIfExists(stagedPath)
            }
        } catch (cleanupFailure: Exception) {
            failure = failure.withSuppressed(cleanupFailure)
        }
        closed = true
        failure?.let { throw it }
    }

    private fun emitRow(row: RelationalRow): Long? {
        check(transaction.isActive) { "No match transaction is active" }
        if (row.operation == RelationalRowOperation.UPDATE) {
            val conditionValues = row.whereValues.filterNotNull()
            write(
                RelationalWriteSupport.updateSql(
                    row.tableName,
                    row.columns,
                    row.whereColumns,
                    row.whereValues
                ),
                *(row.values + conditionValues).toTypedArray()
            )
            return null
        }
        val insertValues = row.columns.zip(row.values).filterNot { (column, _) -> column in row.generatedColumns }
        write(
            RelationalWriteSupport.insertSql(row.tableName, insertValues.map { it.first }),
            *insertValues.map { it.second }.toTypedArray()
        )
        return null
    }

    private data class TransactionSnapshot(val stagedSize: Long)

    private fun write(sql: String, vararg values: Any?) {
        var valueIndex = 0
        val statement = buildString {
            sql.forEach { character ->
                if (character == '?') {
                    require(valueIndex < values.size) {
                        "SQL template has more placeholders than values"
                    }
                    append(toSqlLiteral(values[valueIndex++]))
                } else {
                    append(character)
                }
            }
        }
        require(valueIndex == values.size) {
            "SQL template has fewer placeholders than values"
        }
        writer.appendLine("$statement;")
    }

    private fun toSqlLiteral(value: Any?): String = when (value) {
        null -> "NULL"
        is Boolean -> dialect.booleanLiteral(value)
        is Number -> value.toString()
        is LocalDate -> "'${value}'"
        is LocalDateTime -> "'${value}'"
        else -> "'${value.toString().replace("'", "''")}'"
    }

    private fun Exception?.withSuppressed(failure: Exception): Exception =
        this?.also { it.addSuppressed(failure) } ?: failure

    private companion object {
        fun openWriter(output: Path, append: Boolean = false): BufferedWriter {
            output.parent?.let(Files::createDirectories)
            val options = if (append) {
                arrayOf(
                    java.nio.file.StandardOpenOption.CREATE,
                    java.nio.file.StandardOpenOption.APPEND
                )
            } else {
                arrayOf(
                    java.nio.file.StandardOpenOption.CREATE,
                    java.nio.file.StandardOpenOption.TRUNCATE_EXISTING
                )
            }
            return Files.newBufferedWriter(output, *options)
        }

        fun createStagedPath(output: Path): Path {
            output.parent?.let(Files::createDirectories)
            JournaledMatchReplace.recover(output, JournaledReplaceKind.FILE)
            return Files.createTempFile(output.parent, ".${output.fileName}", ".tmp")
        }

    }

}